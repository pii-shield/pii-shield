package store

import (
	"context"
	"database/sql"
	"errors"
	"regexp"
	"strconv"
	"strings"
)

// The store runs on SQLite (one file, one process) or on Postgres (several
// processes sharing one database). The queries are written once, with ?
// placeholders and nothing either side lacks; dbx and txx rewrite the
// placeholders to $1, $2, ... for Postgres, and the schema is rewritten by
// postgresSchema. An insert reads its id with RETURNING, which both have.

// dbx is a *sql.DB that speaks the store's query dialect.
type dbx struct {
	*sql.DB
	pg bool
}

// txx is a *sql.Tx that speaks the store's query dialect.
type txx struct {
	*sql.Tx
	pg bool
}

func (d *dbx) q(query string) string { return rebind(d.pg, query) }
func (t *txx) q(query string) string { return rebind(t.pg, query) }

func (d *dbx) ExecContext(ctx context.Context, query string, args ...any) (sql.Result, error) {
	return d.DB.ExecContext(ctx, d.q(query), args...)
}

func (d *dbx) QueryContext(ctx context.Context, query string, args ...any) (*sql.Rows, error) {
	return d.DB.QueryContext(ctx, d.q(query), args...)
}

func (d *dbx) QueryRowContext(ctx context.Context, query string, args ...any) *sql.Row {
	return d.DB.QueryRowContext(ctx, d.q(query), args...)
}

func (d *dbx) BeginTx(ctx context.Context, opts *sql.TxOptions) (*txx, error) {
	tx, err := d.DB.BeginTx(ctx, opts)
	if err != nil {
		return nil, err
	}
	return &txx{Tx: tx, pg: d.pg}, nil
}

func (t *txx) ExecContext(ctx context.Context, query string, args ...any) (sql.Result, error) {
	return t.Tx.ExecContext(ctx, t.q(query), args...)
}

func (t *txx) QueryContext(ctx context.Context, query string, args ...any) (*sql.Rows, error) {
	return t.Tx.QueryContext(ctx, t.q(query), args...)
}

func (t *txx) QueryRowContext(ctx context.Context, query string, args ...any) *sql.Row {
	return t.Tx.QueryRowContext(ctx, t.q(query), args...)
}

// rebind turns ? into $n for Postgres, leaving quoted text alone.
func rebind(pg bool, query string) string {
	if !pg || !strings.Contains(query, "?") {
		return query
	}
	var b strings.Builder
	n, quoted := 0, false
	for i := 0; i < len(query); i++ {
		c := query[i]
		switch {
		case c == '\'':
			quoted = !quoted
		case c == '?' && !quoted:
			n++
			b.WriteString("$" + strconv.Itoa(n))
			continue
		}
		b.WriteByte(c)
	}
	return b.String()
}

// IsPostgres reports whether a --db value names a Postgres database.
func IsPostgres(dsn string) bool {
	return strings.HasPrefix(dsn, "postgres://") || strings.HasPrefix(dsn, "postgresql://")
}

var (
	reTrigger = regexp.MustCompile(`(?s)CREATE TRIGGER IF NOT EXISTS (\w+)\s+BEFORE (UPDATE|DELETE) ON (\w+)\s+BEGIN SELECT RAISE\(ABORT, '([^']*)'\); END;`)
	reIDKey   = regexp.MustCompile(`\bid INTEGER PRIMARY KEY\b`)
	reInteger = regexp.MustCompile(`\bINTEGER\b`)
	reBlob    = regexp.MustCompile(`\bBLOB\b`)
)

// postgresSchema rewrites the SQLite schema for Postgres: identity ids,
// BIGINT and BYTEA, the immutability triggers as plpgsql, and the one
// reference SQLite accepts before its table exists (rule_sets points at
// versions, which points back) added once both tables do.
func postgresSchema(sqlite string) string {
	s := reTrigger.ReplaceAllString(sqlite, `CREATE OR REPLACE FUNCTION ${1}_fn() RETURNS trigger LANGUAGE plpgsql AS $$$$ BEGIN RAISE EXCEPTION '${4}'; END $$$$;
DROP TRIGGER IF EXISTS ${1} ON ${3};
CREATE TRIGGER ${1} BEFORE ${2} ON ${3} FOR EACH ROW EXECUTE FUNCTION ${1}_fn();`)
	s = reIDKey.ReplaceAllString(s, "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
	s = reInteger.ReplaceAllString(s, "BIGINT")
	s = reBlob.ReplaceAllString(s, "BYTEA")
	s = strings.Replace(s, "published_version_id BIGINT REFERENCES versions(id),", "published_version_id BIGINT,", 1)
	return s + `
DO $$ BEGIN
	IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'rule_sets_published_version_fk') THEN
		ALTER TABLE rule_sets ADD CONSTRAINT rule_sets_published_version_fk FOREIGN KEY (published_version_id) REFERENCES versions(id);
	END IF;
END $$;
`
}

// schemaLock serializes schema changes of processes starting together on
// one Postgres database.
const schemaLock = 0x70696973 // "piis"

func applyPostgresSchema(ctx context.Context, db *sql.DB, ddl string) error {
	conn, err := db.Conn(ctx)
	if err != nil {
		return err
	}
	defer func() { _ = conn.Close() }()
	if _, err := conn.ExecContext(ctx, `SELECT pg_advisory_lock($1)`, schemaLock); err != nil {
		return err
	}
	defer func() { _, _ = conn.ExecContext(context.Background(), `SELECT pg_advisory_unlock($1)`, schemaLock) }()
	_, err = conn.ExecContext(ctx, ddl)
	return err
}

// lockSet holds the set's row until the transaction ends, so two server
// processes on Postgres number their versions and publications of one set
// one after the other. On SQLite the single connection already does.
func (t *txx) lockSet(ctx context.Context, setID int64) error {
	if !t.pg {
		return nil
	}
	var id int64
	err := t.QueryRowContext(ctx, `SELECT id FROM rule_sets WHERE id = ? FOR UPDATE`, setID).Scan(&id)
	if errors.Is(err, sql.ErrNoRows) {
		return ErrNotFound
	}
	return err
}
